export function currentDateParts(language: Language) {
  const now = new Date();
  return {
    day: String(now.getDate()).padStart(2, "0"),
    detail: new Intl.DateTimeFormat(COPY[language].locale, {
      year: "numeric",
      month: "long",
      weekday: "long",
    }).format(now),
  };
}

export function syncStatusText(
  status: SyncStatus,
  pending: number,
  language: Language,
): { title: string; detail: string } {
  if (language === "en") {
    if (status === "syncing") return { title: "Syncing ciphertext", detail: "Your entries are never sent as plaintext" };
    if (status === "synced") return { title: "Sync complete", detail: "This device and the encrypted server copy are up to date" };
    if (status === "conflict") return { title: "Conflicting entry preserved", detail: "Miroven did not overwrite it automatically" };
    if (status === "error") return { title: "Will retry when connected", detail: `${pending} changes remain safely on this device` };
    if (status === "ready") return { title: "Waiting to sync", detail: `${pending} changes are waiting to be sent` };
    return { title: "Local vault", detail: "Create a recovery code to enable encrypted sync" };
  }
  if (status === "syncing") return { title: "암호문 동기화 중", detail: "기록을 평문으로 보내지 않습니다" };
  if (status === "synced") return { title: "동기화 완료", detail: "이 기기와 서버의 암호문이 최신입니다" };
  if (status === "conflict") return { title: "충돌 기록 보존됨", detail: "자동으로 덮어쓰지 않았습니다" };
  if (status === "error") return { title: "다시 연결하면 재시도", detail: `${pending}개 변경이 기기에 안전하게 남아 있습니다` };
  if (status === "ready") return { title: "동기화 대기", detail: `${pending}개 변경이 전송을 기다립니다` };
  return { title: "현재는 로컬 금고", detail: "복구 코드를 만들면 암호문 동기화가 켜집니다" };
}

